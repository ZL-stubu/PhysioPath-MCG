"""Pure logistic-regression baselines for the two MCG binary tasks.

This module reuses the deterministic NodeEdge NPZ features generated by
``node_edge.py``.  It does not construct a graph, load a neural-network
checkpoint, or import the GNN training code.  The only classifier is
``sklearn.linear_model.LogisticRegression``.
"""

from __future__ import annotations

import argparse
import json
import logging
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Sequence

import joblib
import numpy as np
import pandas as pd
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import (
    accuracy_score,
    average_precision_score,
    balanced_accuracy_score,
    confusion_matrix,
    f1_score,
    precision_score,
    recall_score,
    roc_auc_score,
)
from sklearn.model_selection import StratifiedGroupKFold
from sklearn.pipeline import Pipeline
from sklearn.preprocessing import StandardScaler

from gnn_mcg.configs import LABEL_XLSX, NODE_EDGE_DATA_DIR, REPAIRED_DIR, RESULTS_ROOT
from gnn_mcg.utils import (
    LabelTable,
    SampleMeta,
    discover_samples,
    filter_e1,
    filter_e2_nstemi_stemi,
)


LOG = logging.getLogger("mcg_logistic")
SUMMARY_STAT_NAMES = ("mean", "std", "min", "max", "median", "q25", "q75", "rms")


@dataclass(frozen=True)
class ExperimentSpec:
    """Label mapping and defaults for one binary experiment."""

    name: str
    description: str
    negative_class: str
    positive_class: str
    default_folds: int
    default_output_tag: str


EXPERIMENTS = {
    "e1": ExperimentSpec(
        name="e1",
        description="健康 vs NSTEMI（36 通道 cohort）",
        negative_class="health",
        positive_class="NSTEMI",
        default_folds=5,
        default_output_tag="e1_health_vs_nstemi_logistic",
    ),
    "e2": ExperimentSpec(
        name="e2",
        description="NSTEMI vs STEMI（64 通道 cohort，方案 A）",
        negative_class="NSTEMI",
        positive_class="STEMI",
        default_folds=10,
        default_output_tag="e2_nstemi_vs_stemi_logistic",
    ),
}


def _text_array(values: np.ndarray) -> list[str]:
    return [str(value) for value in np.asarray(values).reshape(-1)]


def _summary_features(blocks: np.ndarray) -> np.ndarray:
    """Summarize the time axis of N×P×L×F NodeEdge features."""
    if blocks.ndim != 4:
        raise ValueError(f"node_feature_blocks 应为四维，实际为 {blocks.shape}")

    # N×P×F×L makes the last axis the time axis for every statistic.
    values = np.transpose(blocks, (0, 1, 3, 2)).astype(np.float64, copy=False)
    q25, median, q75 = np.quantile(values, (0.25, 0.50, 0.75), axis=-1)
    rms = np.sqrt(np.mean(np.square(values), axis=-1))
    summaries = np.stack(
        (
            np.mean(values, axis=-1),
            np.std(values, axis=-1),
            np.min(values, axis=-1),
            np.max(values, axis=-1),
            median,
            q25,
            q75,
            rms,
        ),
        axis=-1,
    )
    return summaries.reshape(-1)


def _feature_names(
    n_rois: int,
    phase_names: Sequence[str],
    signal_names: Sequence[str],
) -> list[str]:
    names: list[str] = []
    for roi_index in range(n_rois):
        for phase_name in phase_names:
            for signal_name in signal_names:
                for statistic in SUMMARY_STAT_NAMES:
                    names.append(
                        f"roi_{roi_index + 1:02d}__{phase_name}__{signal_name}__{statistic}"
                    )

    names.extend(f"phase_duration_ms__{name}" for name in phase_names)
    names.extend(
        (
            "landmark_ms__qrs_onset",
            "landmark_ms__r_peak",
            "landmark_ms__j_point",
            "landmark_ms__t_onset",
            "landmark_ms__t_peak",
            "landmark_ms__t_end",
        )
    )
    names.extend(f"dynamic_active_edge_count__{name}" for name in phase_names)
    return names


def load_node_edge_features(npz_path: Path) -> tuple[np.ndarray, list[str]]:
    """Load one NodeEdge NPZ as a fixed-length sample-level feature vector."""
    required = (
        "node_feature_blocks",
        "node_feature_names",
        "phase_names",
        "phase_duration_ms",
        "landmarks_ms",
        "dynamic_active_edge_counts",
    )
    try:
        with np.load(npz_path, allow_pickle=False) as archive:
            missing = [key for key in required if key not in archive]
            if missing:
                raise KeyError(f"缺少字段：{', '.join(missing)}")

            blocks = np.asarray(archive["node_feature_blocks"], dtype=np.float32)
            phase_names = _text_array(archive["phase_names"])
            signal_names = _text_array(archive["node_feature_names"])
            phase_duration = np.asarray(archive["phase_duration_ms"], dtype=np.float64).reshape(-1)
            landmarks = np.asarray(archive["landmarks_ms"], dtype=np.float64).reshape(-1)
            active_edge_counts = np.asarray(
                archive["dynamic_active_edge_counts"], dtype=np.float64
            ).reshape(-1)
    except (OSError, ValueError, KeyError) as exc:
        raise ValueError(f"无法读取 NodeEdge 特征 {npz_path}: {exc}") from exc

    n_rois, n_phases, _, n_signals = blocks.shape
    if len(phase_names) != n_phases or len(signal_names) != n_signals:
        raise ValueError(f"{npz_path} 的特征名称与特征维度不一致")
    if phase_duration.size != n_phases or active_edge_counts.size != n_phases:
        raise ValueError(f"{npz_path} 的阶段标量维度不一致")
    if landmarks.size != 6:
        raise ValueError(f"{npz_path} 的 landmarks_ms 应含 6 个值")

    vector = np.concatenate(
        (
            _summary_features(blocks),
            phase_duration,
            landmarks,
            active_edge_counts,
        )
    )
    names = _feature_names(n_rois, phase_names, signal_names)
    if vector.size != len(names):
        raise RuntimeError(f"特征值数量 {vector.size} 与名称数量 {len(names)} 不一致")
    if not np.all(np.isfinite(vector)):
        bad_count = int(np.count_nonzero(~np.isfinite(vector)))
        raise ValueError(f"{npz_path} 的样本级特征含 {bad_count} 个 NaN/Inf")
    return vector, names


def build_feature_matrix(samples: Sequence[SampleMeta]) -> tuple[np.ndarray, list[str]]:
    """Read all samples and verify that every NPZ uses the same schema."""
    rows: list[np.ndarray] = []
    expected_names: list[str] | None = None
    total = len(samples)
    for index, sample in enumerate(samples, start=1):
        vector, names = load_node_edge_features(sample.npz_path)
        if expected_names is None:
            expected_names = names
        elif names != expected_names:
            raise ValueError(f"特征 schema 不一致：{sample.npz_path}")
        rows.append(vector)
        if index == 1 or index % 100 == 0 or index == total:
            LOG.info("特征读取进度：%d/%d", index, total)

    if not rows or expected_names is None:
        raise ValueError("没有可用于逻辑回归的样本")
    return np.vstack(rows), expected_names


def prepare_experiment(
    all_samples: Sequence[SampleMeta],
    experiment: str,
) -> tuple[list[SampleMeta], np.ndarray]:
    """Apply the same cohort and label definitions as run_e1.py/run_e2.py."""
    if experiment == "e1":
        samples = filter_e1(all_samples)
        labels = np.asarray([sample.label for sample in samples], dtype=np.int64)
    elif experiment == "e2":
        entries = filter_e2_nstemi_stemi(all_samples)
        samples = [sample for sample, _ in entries]
        # Match run_e2.py方案 A: NSTEMI=0, STEMI=1.
        labels = np.asarray([label for _, label in entries], dtype=np.int64)
    else:
        raise ValueError(f"未知实验：{experiment}")

    if not samples:
        raise ValueError(f"{experiment.upper()} 没有可用样本")
    if np.unique(labels).size != 2:
        raise ValueError(f"{experiment.upper()} 需要两个类别，实际标签为 {np.unique(labels)}")
    return samples, labels


def patient_level_splits(
    samples: Sequence[SampleMeta],
    labels: np.ndarray,
    requested_folds: int,
    seed: int,
) -> tuple[list[tuple[np.ndarray, np.ndarray]], int, dict[int, int]]:
    """Create stratified folds while keeping every patient in one fold."""
    if requested_folds < 2:
        raise ValueError("folds 至少为 2")

    patient_labels: dict[str, int] = {}
    for sample, label in zip(samples, labels, strict=True):
        previous = patient_labels.setdefault(sample.patient_key, int(label))
        if previous != int(label):
            raise ValueError(f"同一患者 {sample.patient_key} 出现冲突标签")

    patient_class_counts = {
        class_id: sum(label == class_id for label in patient_labels.values())
        for class_id in (0, 1)
    }
    max_folds = min(patient_class_counts.values())
    if max_folds < 2:
        raise ValueError(f"每类至少需要 2 位患者，实际为 {patient_class_counts}")

    effective_folds = min(requested_folds, max_folds)
    if effective_folds != requested_folds:
        LOG.warning(
            "请求 %d 折，但最少类别仅有 %d 位患者；自动改为 %d 折。",
            requested_folds,
            max_folds,
            effective_folds,
        )

    groups = np.asarray([sample.patient_key for sample in samples], dtype=str)
    splitter = StratifiedGroupKFold(
        n_splits=effective_folds,
        shuffle=True,
        random_state=seed,
    )
    dummy = np.zeros(labels.size, dtype=np.uint8)
    splits = list(splitter.split(dummy, labels, groups))
    return splits, effective_folds, patient_class_counts


def make_classifier(
    c_value: float,
    max_iter: int,
    seed: int,
    balanced: bool,
) -> Pipeline:
    """Build preprocessing plus the single allowed classifier."""
    if c_value <= 0:
        raise ValueError("C 必须大于 0")
    if max_iter <= 0:
        raise ValueError("max_iter 必须大于 0")
    return Pipeline(
        steps=(
            ("scale", StandardScaler()),
            (
                "logistic_regression",
                LogisticRegression(
                    penalty="l2",
                    C=c_value,
                    solver="liblinear",
                    dual=True,
                    class_weight="balanced" if balanced else None,
                    max_iter=max_iter,
                    random_state=seed,
                ),
            ),
        )
    )


def binary_metrics(
    true_labels: np.ndarray,
    predictions: np.ndarray,
    positive_probabilities: np.ndarray,
) -> dict[str, float | int]:
    """Calculate binary metrics with class 1 treated as positive."""
    tn, fp, fn, tp = confusion_matrix(true_labels, predictions, labels=(0, 1)).ravel()
    specificity_denominator = int(tn + fp)
    specificity = float(tn / specificity_denominator) if specificity_denominator else float("nan")
    return {
        "n_samples": int(true_labels.size),
        "accuracy": float(accuracy_score(true_labels, predictions)),
        "balanced_accuracy": float(balanced_accuracy_score(true_labels, predictions)),
        "roc_auc": float(roc_auc_score(true_labels, positive_probabilities)),
        "average_precision": float(average_precision_score(true_labels, positive_probabilities)),
        "precision": float(precision_score(true_labels, predictions, zero_division=0)),
        "sensitivity_recall": float(recall_score(true_labels, predictions, zero_division=0)),
        "specificity": specificity,
        "f1": float(f1_score(true_labels, predictions, zero_division=0)),
        "tn": int(tn),
        "fp": int(fp),
        "fn": int(fn),
        "tp": int(tp),
    }


def _json_ready(value: object) -> object:
    if isinstance(value, dict):
        return {str(key): _json_ready(item) for key, item in value.items()}
    if isinstance(value, (list, tuple)):
        return [_json_ready(item) for item in value]
    if isinstance(value, np.generic):
        return value.item()
    return value


def run_cross_validation(
    samples: Sequence[SampleMeta],
    labels: np.ndarray,
    features: np.ndarray,
    feature_names: Sequence[str],
    spec: ExperimentSpec,
    output_dir: Path,
    folds: int,
    seed: int,
    c_value: float,
    max_iter: int,
    balanced: bool,
    top_features: int,
) -> dict[str, object]:
    """Run patient-level OOF evaluation, then fit one final logistic model."""
    splits, effective_folds, patient_class_counts = patient_level_splits(
        samples, labels, folds, seed
    )
    output_dir.mkdir(parents=True, exist_ok=True)

    oof_prediction = np.full(labels.shape, -1, dtype=np.int64)
    oof_probability = np.full(labels.shape, np.nan, dtype=np.float64)
    fold_assignment = np.full(labels.shape, -1, dtype=np.int64)
    fold_rows: list[dict[str, float | int]] = []

    for fold_index, (train_indices, validation_indices) in enumerate(splits, start=1):
        classifier = make_classifier(c_value, max_iter, seed + fold_index, balanced)
        classifier.fit(features[train_indices], labels[train_indices])
        predictions = classifier.predict(features[validation_indices]).astype(np.int64)
        probabilities = classifier.predict_proba(features[validation_indices])[:, 1]

        oof_prediction[validation_indices] = predictions
        oof_probability[validation_indices] = probabilities
        fold_assignment[validation_indices] = fold_index
        metrics = binary_metrics(labels[validation_indices], predictions, probabilities)
        metrics.update(
            {
                "fold": fold_index,
                "n_train": int(train_indices.size),
                "n_validation": int(validation_indices.size),
            }
        )
        fold_rows.append(metrics)
        LOG.info(
            "Fold %d/%d: n=%d, balanced_accuracy=%.4f, roc_auc=%.4f",
            fold_index,
            effective_folds,
            validation_indices.size,
            metrics["balanced_accuracy"],
            metrics["roc_auc"],
        )

    if np.any(oof_prediction < 0) or np.any(~np.isfinite(oof_probability)):
        raise RuntimeError("交叉验证未覆盖全部样本")

    oof_metrics = binary_metrics(labels, oof_prediction, oof_probability)
    predictions_table = pd.DataFrame(
        {
            "fold": fold_assignment,
            "sample_id": [sample.sample_id for sample in samples],
            "patient_key": [sample.patient_key for sample in samples],
            "group": [sample.group for sample in samples],
            "non_nstemi_subcategory": [sample.non_nstemi_subcat for sample in samples],
            "true_label": labels,
            "true_class": [
                spec.positive_class if label == 1 else spec.negative_class for label in labels
            ],
            "predicted_label": oof_prediction,
            "predicted_class": [
                spec.positive_class if label == 1 else spec.negative_class
                for label in oof_prediction
            ],
            f"probability_{spec.positive_class}": oof_probability,
            "node_edge_npz": [str(sample.npz_path) for sample in samples],
        }
    )
    predictions_table.to_csv(
        output_dir / "cross_validation_predictions.csv",
        index=False,
        encoding="utf-8-sig",
    )

    fold_table = pd.DataFrame(fold_rows).sort_values("fold")
    fold_table.to_csv(output_dir / "fold_metrics.csv", index=False, encoding="utf-8-sig")
    pd.DataFrame({"feature_name": feature_names}).to_csv(
        output_dir / "feature_names.csv", index=False, encoding="utf-8-sig"
    )

    final_classifier = make_classifier(c_value, max_iter, seed, balanced)
    final_classifier.fit(features, labels)
    artifact = {
        "pipeline": final_classifier,
        "experiment": spec.name,
        "class_names": {0: spec.negative_class, 1: spec.positive_class},
        "feature_names": list(feature_names),
        "feature_source": "node_edge.py NodeEdge NPZ summary features",
    }
    joblib.dump(artifact, output_dir / "final_logistic_regression.joblib")

    logistic = final_classifier.named_steps["logistic_regression"]
    coefficients = np.asarray(logistic.coef_[0], dtype=np.float64)
    coefficient_table = pd.DataFrame(
        {
            "feature_name": feature_names,
            "standardized_coefficient": coefficients,
            "absolute_coefficient": np.abs(coefficients),
            "direction": np.where(coefficients >= 0, spec.positive_class, spec.negative_class),
        }
    ).sort_values("absolute_coefficient", ascending=False)
    coefficient_table.head(max(0, top_features)).to_csv(
        output_dir / "top_coefficients.csv", index=False, encoding="utf-8-sig"
    )

    metric_columns = (
        "accuracy",
        "balanced_accuracy",
        "roc_auc",
        "average_precision",
        "precision",
        "sensitivity_recall",
        "specificity",
        "f1",
    )
    fold_mean = {name: float(fold_table[name].mean()) for name in metric_columns}
    fold_std = {name: float(fold_table[name].std(ddof=1)) for name in metric_columns}
    summary: dict[str, object] = {
        "experiment": spec.name,
        "description": spec.description,
        "classifier": "sklearn.linear_model.LogisticRegression (L2)",
        "negative_class_0": spec.negative_class,
        "positive_class_1": spec.positive_class,
        "n_samples": len(samples),
        "n_features": int(features.shape[1]),
        "requested_folds": folds,
        "effective_folds": effective_folds,
        "patient_counts_by_class": patient_class_counts,
        "seed": seed,
        "C": c_value,
        "max_iter": max_iter,
        "class_weight": "balanced" if balanced else None,
        "oof_metrics": oof_metrics,
        "fold_metric_mean": fold_mean,
        "fold_metric_std": fold_std,
    }
    with (output_dir / "summary.json").open("w", encoding="utf-8") as handle:
        json.dump(_json_ready(summary), handle, ensure_ascii=False, indent=2, allow_nan=False)

    LOG.info(
        "OOF 完成：balanced_accuracy=%.4f, roc_auc=%.4f",
        oof_metrics["balanced_accuracy"],
        oof_metrics["roc_auc"],
    )
    return summary


def build_parser(fixed_experiment: str | None = None) -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="仅使用单一逻辑回归完成 MCG 二分类（不调用 GNN/深度学习模型）。"
    )
    if fixed_experiment is None:
        parser.add_argument("--experiment", choices=tuple(EXPERIMENTS), required=True)
    parser.add_argument("--folds", type=int, default=None, help="患者级分层交叉验证折数")
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--C", dest="c_value", type=float, default=1.0)
    parser.add_argument("--max-iter", type=int, default=5000)
    parser.add_argument(
        "--unweighted",
        action="store_true",
        help="关闭默认的 class_weight='balanced'",
    )
    parser.add_argument("--top-features", type=int, default=100)
    parser.add_argument("--label-xlsx", type=Path, default=LABEL_XLSX)
    parser.add_argument("--repaired-dir", type=Path, default=REPAIRED_DIR)
    parser.add_argument("--node-edge-dir", type=Path, default=NODE_EDGE_DATA_DIR)
    parser.add_argument("--output-dir", type=Path, default=None)
    parser.add_argument(
        "--log-level",
        choices=("DEBUG", "INFO", "WARNING", "ERROR"),
        default="INFO",
    )
    return parser


def main(
    argv: Sequence[str] | None = None,
    fixed_experiment: str | None = None,
) -> int:
    parser = build_parser(fixed_experiment)
    args = parser.parse_args(argv)
    experiment = fixed_experiment or args.experiment
    spec = EXPERIMENTS[experiment]

    logging.basicConfig(
        level=getattr(logging, args.log_level),
        format="%(asctime)s | %(levelname)s | %(name)s | %(message)s",
        datefmt="%Y-%m-%d %H:%M:%S",
    )

    folds = args.folds if args.folds is not None else spec.default_folds
    output_dir = args.output_dir or RESULTS_ROOT / spec.default_output_tag
    try:
        labels = LabelTable(args.label_xlsx)
        all_samples = discover_samples(
            repaired_dir=args.repaired_dir,
            node_edge_dir=args.node_edge_dir,
            labels=labels,
        )
        samples, targets = prepare_experiment(all_samples, experiment)
        class_counts = np.bincount(targets, minlength=2)
        LOG.info(
            "%s: %d samples (%s=%d, %s=%d)",
            spec.description,
            len(samples),
            spec.negative_class,
            class_counts[0],
            spec.positive_class,
            class_counts[1],
        )
        features, feature_names = build_feature_matrix(samples)
        LOG.info("样本级特征矩阵：%s", features.shape)
        run_cross_validation(
            samples=samples,
            labels=targets,
            features=features,
            feature_names=feature_names,
            spec=spec,
            output_dir=output_dir,
            folds=folds,
            seed=args.seed,
            c_value=args.c_value,
            max_iter=args.max_iter,
            balanced=not args.unweighted,
            top_features=args.top_features,
        )
        LOG.info("结果已保存到：%s", output_dir)
        return 0
    except Exception as exc:
        LOG.exception("逻辑回归运行失败：%s", exc)
        return 1


if __name__ == "__main__":
    sys.exit(main())
